import 'package:flutter/material.dart';

import 'app_tokens.dart';

/// The five vocabulary levels words are grouped into.
///
/// A level is a share of **running Japanese**, measured on the BCCWJ corpus by
/// the content pipeline. Level 1 is the 750 commonest words, which are 51.2% of
/// everything written; level 5 is the long tail of 4,500, which adds 1.5%.
///
/// Vocabulary has no JLPT level and this is why. The JLPT publishes an official
/// kanji list but no vocabulary list, so every dataset's "N5 word" is a guess
/// by whoever compiled it. Kanji keep [levelColor] and their real levels; words
/// get a measured level that says what it means.
///
/// The level replaced a `difficulty_tier` that banded words by share of our own
/// word list. A tier meant "the easiest fifth of whatever we happen to ship",
/// which is a fact about the app rather than about Japanese.
const int kVocabularyLevelCount = 5;

const List<int> kAllVocabularyLevels = [1, 2, 3, 4, 5];

/// The level's fill colour in the current theme.
///
/// A sequential ramp rather than a set of categories, because a level is a
/// magnitude: level 3 really does sit between level 2 and level 4, and a single
/// hue is the only honest way to draw that. Each theme builds its ramp around
/// its own primary, dark to light in light mode and light to dark in dark mode,
/// so the darkest step never disappears against a dark surface
/// (`AppTokens.levelRamp`, generated by `scripts/design/theme_palettes.py`).
Color vocabularyLevelColor(int level, AppTokens tokens) {
  final List<Color> ramp = tokens.levelRamp;
  return ramp[(level - 1).clamp(0, ramp.length - 1)];
}

/// The readable foreground on [vocabularyLevelColor], chosen by true WCAG
/// contrast rather than a brightness threshold, which lands on the wrong side
/// for the mid-tones of these ramps.
Color onVocabularyLevelColor(int level, AppTokens tokens) =>
    onAccentFor(vocabularyLevelColor(level, tokens));

/// Filled dots on a level card, 1 through 5.
int vocabularyLevelDifficulty(int level) =>
    level >= 1 && level <= kVocabularyLevelCount ? level : -1;
